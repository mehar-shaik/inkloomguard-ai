-- InkloomGuard AI — Authentication & Account Security Tokens Migration
-- Strictly additive & idempotent: preserves all existing users, roles, and sessions.
-- Existing unverified accounts remain unverified (email_verified = FALSE) with verification_required = FALSE
-- so no existing users are silently marked verified or unexpectedly locked out.

-- 1. Account verification & session invalidation fields on users
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS verification_required BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS token_version INTEGER NOT NULL DEFAULT 1;
ALTER TABLE users ADD COLUMN IF NOT EXISTS password_updated_at TIMESTAMPTZ;

-- 2. Single-use, time-limited password reset tokens (SHA-256 hash stored, never plaintext)
CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  requested_ip TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- token_hash TEXT NOT NULL UNIQUE already creates a unique index; no separate hash index needed
CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_user_expires
  ON password_reset_tokens(user_id, company_id, expires_at);

-- 3. Single-use, time-limited email verification tokens (SHA-256 hash stored, never plaintext)
CREATE TABLE IF NOT EXISTS email_verification_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_email_verification_tokens_user_expires
  ON email_verification_tokens(user_id, company_id, expires_at);
