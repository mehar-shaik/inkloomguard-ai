-- InkloomGuard AI — Storage Metadata & Migration Tracking
-- Associates every uploaded file with its company, brand, original filename, MIME type, and storage path.

CREATE TABLE IF NOT EXISTS stored_files (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  brand_id BIGINT NOT NULL REFERENCES brands(id) ON DELETE CASCADE,
  submission_id BIGINT REFERENCES submissions(id) ON DELETE CASCADE,
  guideline_document_id BIGINT REFERENCES guideline_documents(id) ON DELETE CASCADE,
  asset_kind TEXT NOT NULL,
  storage_backend TEXT NOT NULL DEFAULT 'supabase',
  storage_key TEXT NOT NULL,
  filename TEXT NOT NULL,
  original_name TEXT NOT NULL,
  mime_type TEXT NOT NULL,
  size_bytes BIGINT NOT NULL DEFAULT 0,
  uploaded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_stored_files_company ON stored_files(company_id);
CREATE INDEX IF NOT EXISTS idx_stored_files_filename ON stored_files(filename, company_id);
CREATE INDEX IF NOT EXISTS idx_stored_files_brand ON stored_files(brand_id, company_id);
